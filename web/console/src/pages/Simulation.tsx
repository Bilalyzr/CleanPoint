import React from "react";
import { useNavigate } from "react-router-dom";
import { api, SimJob, SCENARIO_FAMILIES, fmtTime } from "../api";
import { Chip, Banner, KV } from "../components";
import { Session } from "../App";

const FAMILY_NOTES: Record<string, string> = {
  normal_office: "benign · steady office activity — expect no onset, newest eligible",
  benign_archive: "benign · a few high-entropy archives appear — must NOT be treated as an attack",
  benign_bulk_update: "benign · large software-update burst — safe under the validated threshold",
  rapid_destructive: "attack-like · fast mass rewrite — older clean candidate expected",
  slow_distributed: "attack-like · cumulative low-rate changes across hosts — cumulative detection",
  extension_churn: "attack-like · mass renames to random extensions — not signature dependent",
  mixed_activity: "benign burst + destructive window — onset must land on the attack, not the burst",
  pre_existing_contamination: "contamination predates every snapshot — must ABSTAIN (no_safe_candidate)",
};

// UI-05: scenario family, seed, simulated clock phases, Run/Reset;
// explicit "synthetic only" labeling; operator-only.
export default function Simulation() {
  const nav = useNavigate();
  const { role } = React.useContext(Session);
  const [scenario, setScenario] = React.useState("rapid_destructive");
  const [seed, setSeed] = React.useState(1);
  const [job, setJob] = React.useState<SimJob | null>(null);
  const [history, setHistory] = React.useState<SimJob[]>([]);
  const [err, setErr] = React.useState("");
  const isOperator = role === "operator";

  const loadHistory = React.useCallback(() => {
    api<{ simulations: SimJob[] }>("GET", "/simulations")
      .then((d) => setHistory(d.simulations ?? []))
      .catch(() => {});
  }, []);
  React.useEffect(loadHistory, [loadHistory]);

  // poll the running job until it settles
  React.useEffect(() => {
    if (!job || job.status !== "running") return;
    const t = setInterval(async () => {
      try {
        const j = await api<SimJob>("GET", `/simulations/${job.id}`);
        setJob(j);
        if (j.status !== "running") loadHistory();
      } catch {
        /* keep polling */
      }
    }, 1500);
    return () => clearInterval(t);
  }, [job, loadHistory]);

  const run = async () => {
    setErr("");
    try {
      const j = await api<SimJob>("POST", "/simulate", { scenario, seed });
      setJob(j);
    } catch (e) {
      setErr(e instanceof Error ? e.message : String(e));
    }
  };

  const result = job?.result;
  const logHas = (j: SimJob | null, re: RegExp) => j?.log.some((l) => re.test(l)) ?? false;
  return (
    <>
      <h2 className="page">Simulation Lab</h2>
      <Banner tone="info" title="SYNTHETIC ONLY — safe scenario replay">
        Everything here is harmless seeded data generated by the deterministic Python simulator.
        A run takes ~45–60 seconds: it registers a fresh workload, seals 13 snapshots across a
        simulated timeline, analyzes, and (when a candidate exists) performs a verified restore.
      </Banner>
      {!isOperator && (
        <Banner tone="warn" title="Read-only role">
          Running simulations requires the operator token. You can still inspect results below.
        </Banner>
      )}
      <div className="card">
        <div className="sim-grid">
          <div>
            <label className="fld" htmlFor="fam">Scenario family</label>
            <select id="fam" value={scenario} onChange={(e) => setScenario(e.target.value)} disabled={!isOperator}>
              {SCENARIO_FAMILIES.map((f) => (
                <option key={f} value={f}>{f}</option>
              ))}
            </select>
            <p className="hint" style={{ marginTop: 8 }}>{FAMILY_NOTES[scenario]}</p>
          </div>
          <div>
            <label className="fld" htmlFor="seed">Seed (1–999, deterministic)</label>
            <input
              id="seed"
              type="number"
              min={1}
              max={999}
              value={seed}
              onChange={(e) => setSeed(Math.max(1, Math.min(999, Number(e.target.value) || 1)))}
              disabled={!isOperator}
            />
            <p className="hint" style={{ marginTop: 8 }}>Same family + seed ⇒ identical bytes, events and outcome, every time.</p>
          </div>
        </div>
        <div style={{ display: "flex", gap: 10, marginTop: 16 }}>
          <button className="btn primary" onClick={run} disabled={!isOperator || job?.status === "running"}>
            {job?.status === "running" ? "Running…" : "Run scenario"}
          </button>
          {job && job.status !== "running" && (
            <button className="btn" onClick={() => setJob(null)}>Reset</button>
          )}
        </div>
        <p className="login-error" role="alert">{err}</p>
      </div>

      {job && (
        <div className="card">
          <div className="job-head">
            <h3 className="sec" style={{ margin: 0 }}>Simulation job</h3>
            <span className="mono-id">{job.id}</span>
            <Chip kind={job.status === "completed" ? "verified" : job.status === "failed" ? "failed" : "warn"} label={job.status} />
          </div>
          <KV
            rows={[
              ["Scenario / seed", `${job.scenario} · seed ${job.seed}`],
              ["Started", fmtTime(job.started_at)],
              ["Finished", job.finished_at ? fmtTime(job.finished_at) : "—"],
            ]}
          />
          {job.status === "running" && (
            <>
              <div className="stepper" aria-hidden="true">
                <div className="step done">generate</div>
                <div className={logHas(job, /window\s+(3[0-9]|[2-9]\d)/) ? "done" : "active"}>ingest + seal ×13</div>
                <div className="">analyze</div>
                <div className="">select</div>
                <div className="">restore</div>
              </div>
              <p className="hint">Simulated clock running through 40 windows (13 snapshot points) — about 45–60 s total.</p>
            </>
          )}
          {job.status === "failed" && <Banner tone="error" title="Simulation failed">{job.error}</Banner>}
          {result && (
            <>
              <h3 className="sec">Outcome</h3>
              <KV
                rows={[
                  ["Workload", <span className="path">{String(result.workload_id ?? "—")}</span>],
                  ["Selector", <Chip kind={result.selector_status === "candidate_available" ? "eligible" : "no_safe_candidate"} label={String(result.selector_status)} />],
                  ["Recommended contaminated?", result.recommended_contaminated == null ? "n/a (abstained)" : String(result.recommended_contaminated)],
                  ["Onset (detector) vs truth (hidden)", `${result.onset ?? "none"} vs ${result.attack_start ?? "none"}`],
                  ["Restore", result.restore ? `${result.restore.status} · ${result.restore.verified_files} verified · source unchanged: ${result.restore.source_unchanged}` : "not performed"],
                ]}
              />
              {result.workload_id && (
                <p className="hint">
                  <button className="btn" onClick={() => nav(`/workload/${result.workload_id}/overview`)}>
                    Open workload →
                  </button>
                </p>
              )}
            </>
          )}
          {job.log.length > 0 && (
            <details>
              <summary>Driver log ({job.log.length} lines)</summary>
              <pre className="term">{job.log.join("\n")}</pre>
            </details>
          )}
        </div>
      )}

      <h3 className="sec">Recent simulations</h3>
      {history.length === 0 ? (
        <div className="empty">No simulations started from this console yet.</div>
      ) : (
        <table className="tbl">
          <thead>
            <tr>
              <th>Job</th>
              <th>Scenario</th>
              <th className="num">Seed</th>
              <th>Status</th>
              <th>Started</th>
            </tr>
          </thead>
          <tbody>
            {history.map((j) => (
              <tr key={j.id}>
                <td className="path">{j.id}</td>
                <td>{j.scenario}</td>
                <td className="num">{j.seed}</td>
                <td><Chip kind={j.status === "completed" ? "verified" : j.status === "failed" ? "failed" : "warn"} label={j.status} /></td>
                <td>{fmtTime(j.started_at)}</td>
              </tr>
            ))}
          </tbody>
        </table>
      )}
    </>
  );
}
